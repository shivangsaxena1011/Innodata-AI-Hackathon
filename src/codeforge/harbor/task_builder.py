"""Assemble a Harbor task directory.

The skeleton comes from the official CLI (`harbor init <org>/<name> --task`), then CodeForge
fills in instruction, environment, solution, tests, task.toml and evidence. Scaffold files
CodeForge does not use (the pytest template) are removed.
"""

from __future__ import annotations

import json
import logging
import shutil
from pathlib import Path

from codeforge.adapters.languages.base import LanguageAdapter
from codeforge.harbor import metadata_builder, solution_packager, test_packager
from codeforge.harbor.harbor_validator import _env as harbor_env
from codeforge.harbor.harbor_validator import harbor_executable
from codeforge.schemas.repository import RepositoryProfile
from codeforge.schemas.task import GeneratedTask
from codeforge.utils import fs
from codeforge.utils.proc import run

log = logging.getLogger(__name__)


def _scaffold(org: str, task: GeneratedTask, parent: Path) -> Path:
    task_dir = parent / task.task_id
    fs.rmtree(task_dir)
    exe = harbor_executable()
    if exe:
        r = run([exe, "init", f"{org}/{task.task_id}", "--task", "-o", str(parent),
                 "--include-standard-metadata", "--description", task.spec.summary[:200]],
                timeout=120, env=harbor_env())
        if not r.ok:
            log.warning("harbor init failed (%s); writing the skeleton directly", r.output[-300:])
    task_dir.mkdir(parents=True, exist_ok=True)
    for leftover in ("tests/test_outputs.py",):
        (task_dir / leftover).unlink(missing_ok=True)
    return task_dir


def build_task(
    org: str,
    task: GeneratedTask,
    profile: RepositoryProfile,
    adapter: LanguageAdapter,
    env_dir: Path,
    snapshot: Path,
    regression_paths: list[str],
    out_parent: Path,
    validation_summary: dict,
    generation: dict,
    evidence_dir: Path | None = None,
) -> Path:
    task_dir = _scaffold(org, task, out_parent)
    fs.write_text_lf(task_dir / "instruction.md", task.instruction)

    env_target = task_dir / "environment"
    fs.rmtree(env_target)
    shutil.copytree(env_dir, env_target)
    env_dockerfile = (env_dir / "Dockerfile").read_text(encoding="utf-8")
    base_image = env_dockerfile.splitlines()[0].removeprefix("FROM ").strip()

    solution_packager.write_solution(task_dir, task.reference)
    test_packager.write_tests(task_dir, task, profile, adapter, snapshot, env_dockerfile,
                              regression_paths)
    fs.write_text_lf(task_dir / "task.toml", metadata_builder.build_task_toml(
        org, task, profile, validation_summary))
    manifest = metadata_builder.build_manifest(task, profile, base_image, validation_summary,
                                               generation)
    fs.write_text_lf(task_dir / "task_manifest.json", json.dumps(manifest, indent=2))
    fs.write_text_lf(task_dir / "README.md", _readme(task, profile, validation_summary))
    if evidence_dir and evidence_dir.exists():
        target = task_dir / "validation"
        fs.rmtree(target)
        shutil.copytree(evidence_dir, target, ignore=shutil.ignore_patterns("container.log"))
    return task_dir


def _readme(task: GeneratedTask, profile: RepositoryProfile, summary: dict) -> str:
    gates = "\n".join(f"| {g['gate']} | {g['status']} | {g['summary']} |"
                      for g in summary.get("gates", []))
    return f"""# {task.title}

Generated by **CodeForge AI** (Team TECH TITAN).

- Repository: `{profile.repository_url}`
- Starting commit: `{profile.starting_commit_sha}`
- Archetype: `{task.archetype.value}` · Language: `{profile.primary_language}`
- Validity score: **{summary.get('validity_score', 'n/a')}** (status: {summary.get('status')})

## Layout

| Path | Purpose |
|---|---|
| `instruction.md` | What the agent sees |
| `environment/` | Agent sandbox: Dockerfile + repository snapshot (no git history) |
| `solution/solve.sh` | Reference solution used by Harbor's oracle agent |
| `tests/` | Separate verifier: hidden feature tests, pristine regression tests, grader |
| `task_manifest.json` | Full provenance: commit, environment, tests, validation |
| `validation/` | Raw evidence from CodeForge's validation runs |

## Validation gates

| Gate | Status | Summary |
|---|---|---|
{gates}

## Run it

```bash
harbor lint .
harbor run -p . -a oracle   # reference solution, expected reward 1.0
harbor run -p . -a nop      # no changes, expected reward 0.0
```
"""
